def observe(pos, gt):
    r, c = pos
    return np.clip(gt[r, c] + np.random.normal(0, SENSOR_NOISE_SD), 0, 1)

def bayesian_spatial_update(prior, prior_var, observations, obs_positions):
    rows, cols = np.ogrid[:GRID_H, :GRID_W]
    lsum = np.zeros((GRID_H, GRID_W))
    lwt  = np.zeros((GRID_H, GRID_W))
    for (r, c), obs in zip(obs_positions, observations):
        w = np.exp(-((rows - r)**2 + (cols - c)**2) / (2 * INFLUENCE_SIGMA**2))
        lsum += w * obs
        lwt  += w
    post_mean = np.where(lwt > 1e-6,
        (prior / prior_var + lsum / (SENSOR_NOISE_SD**2 + 1e-9)) /
        (1 / prior_var     + lwt  / (SENSOR_NOISE_SD**2 + 1e-9)), prior)
    post_var  = np.where(lwt > 1e-6,
        1.0 / (1 / prior_var + lwt / (SENSOR_NOISE_SD**2 + 1e-9)), prior_var)
    return np.clip(post_mean, 0, 1), np.clip(post_var, 1e-4, 1)

def kalman_update(kf_m, kf_v, measurement, meas_noise=0.05**2, process_noise=0.005):
    kf_v_pred = kf_v + process_noise
    K     = kf_v_pred / (kf_v_pred + meas_noise)
    kf_m_ = kf_m + K * (measurement - kf_m)
    kf_v_ = (1 - K) * kf_v_pred
    return np.clip(kf_m_, 0, 1), np.clip(kf_v_, 1e-4, 1)

def reallocate_sensors(positions, risk_map, var_map, low_thresh=LOW_THRESH, high_thresh=HIGH_THRESH):
    """Move DEALLOC_FRAC fraction of sensors. TOTAL count stays = N_SENSORS.
    Returns (new_positions, moves, movement_reasons) where movement_reasons
    explains WHY each sensor moved — for explainability / PM demo.
    """
    n_move = max(1, int(N_SENSORS * DEALLOC_FRAC))
    moves  = []
    movement_reasons = []

    def acq(r, c):
        return ALPHA_ACQ * risk_map[r, c] + BETA_ACQ * np.sqrt(var_map[r, c])

    def reason_str(r, c):
        rv = risk_map[r, c]; uv = np.sqrt(var_map[r, c])
        if rv >= high_thresh and uv > 0.3:
            return "high risk + high uncertainty"
        elif rv >= high_thresh:
            return "high risk — exploit known hotspot"
        elif uv > 0.3:
            return "high uncertainty — explore unknown area"
        elif rv >= low_thresh:
            return "medium risk — monitoring"
        else:
            return "low value — reassigned elsewhere"

    expendability = sorted([(acq(r, c), idx) for idx, (r, c) in enumerate(positions)])
    move_indices  = [idx for (_, idx) in expendability[:n_move]]
    scores = np.array([[acq(r, c) for c in range(GRID_W)] for r in range(GRID_H)])
    flat_idx      = np.argsort(scores.ravel())[::-1]
    target_coords = np.array([np.unravel_index(i, scores.shape) for i in flat_idx[:50]])
    new_positions = positions.copy()
    for idx in move_indices:
        old_r, old_c = positions[idx]
        t = target_coords[np.random.randint(len(target_coords))]
        new_positions[idx] = t
        new_r, new_c = int(t[0]), int(t[1])
        moves.append((old_r, old_c, new_r, new_c))
        movement_reasons.append({
            "sensor_id":       idx + 1,
            "from":            [old_r, old_c],
            "to":              [new_r, new_c],
            "movement_reason": reason_str(new_r, new_c),
        })
    # Stationary sensors also get a reason
    for idx in range(len(positions)):
        if idx not in move_indices:
            r, c = positions[idx]
            movement_reasons.append({
                "sensor_id":       idx + 1,
                "from":            [int(r), int(c)],
                "to":              [int(r), int(c)],
                "movement_reason": reason_str(r, c) + " — held in place",
            })
    assert len(new_positions) == N_SENSORS, "Sensor count changed!"
    return new_positions, moves, movement_reasons

