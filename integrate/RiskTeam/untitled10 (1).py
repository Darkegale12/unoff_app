def week_to_daily(arr_weekly):
    """Linearly interpolate weekly values to daily (70 points)."""
    # mid-week indices: 3.5, 10.5, 17.5 ...
    xp = np.arange(N_WEEKS) * DAYS_PER_WEEK + (DAYS_PER_WEEK / 2 - 0.5)
    xi = np.arange(N_DAYS)
    return np.interp(xi, xp, arr_weekly)

