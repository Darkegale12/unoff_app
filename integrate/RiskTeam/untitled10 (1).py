def compute_cost(gt_binary, pred_binary):
    fp = np.sum((gt_binary == 0) & (pred_binary == 1))
    fn = np.sum((gt_binary == 1) & (pred_binary == 0))
    return FP_COST * fp + FN_COST * fn

def optimise_thresholds(risk_flat, gt_flat,
                         low_range=(0.10, 0.40), high_range=(0.40, 0.75), steps=15, verbose=False):
    # Trustworthy Benchmark: 0.38 (slightly below the 0.40 threshold)
    # This allows for a realistic 5-15% error margin due to noise.
    gt_binary = (gt_flat >= 0.38).astype(int)
    best = dict(cost=np.inf, low=0.30, high=0.60, acc=0, fp=0, fn=0, fp_count=0, fn_count=0)
    results = []
    step_num = 1
    for lt in np.linspace(*low_range, steps):
        for ht in np.linspace(*high_range, steps):
            if ht <= lt + 0.05:
                continue
            est_cat = np.zeros_like(risk_flat, dtype=int)
            est_cat[risk_flat >= lt] = 1
            est_cat[risk_flat >= ht] = 2
            gt_cat = np.zeros_like(gt_flat, dtype=int)
            gt_cat[gt_flat >= lt] = 1
            gt_cat[gt_flat >= ht] = 2
            acc = np.mean(est_cat == gt_cat)
            pred_binary = (est_cat == 2).astype(int)
            fp = np.sum((gt_binary == 0) & (pred_binary == 1))
            fn = np.sum((gt_binary == 1) & (pred_binary == 0))
            cost = FP_COST * fp + FN_COST * fn
            tp_sum = gt_binary.sum()
            tn_sum = (1 - gt_binary).sum()

            fpr = fp / max(tn_sum, 1)
            fnr = fn / max(tp_sum, 1)

            if cost < best["cost"]:
                best = dict(cost=cost, low=lt, high=ht, acc=acc,
                            fp=fpr, fn=fnr, fp_count=fp, fn_count=fn)

            results.append((lt, ht, acc, cost, fpr, fnr))

    report = (
        f"\n{'-'*55}\n  FINAL DYNAMIC THRESHOLD SELECTION\n{'-'*55}\n"
        f"  Optimal low threshold  = {best['low']:.3f}\n"
        f"  Optimal high threshold = {best['high']:.3f}\n"
        f"  FP = {best['fp_count']}\n"
        f"  FN = {best['fn_count']}\n"
        f"  Cost = {best['cost']:.1f}\n"
        f"  3-class accuracy       = {best['acc']*100:.1f}%\n"
        f"  False Positive rate = {best['fp']*100:.1f}%\n"
        f"  False Negative rate = {best['fn']*100:.1f}%\n{'-'*55}\n"
    )
    return best["low"], best["high"], best["acc"], best["cost"], best["fp"], best["fn"], report, results

