def make_ground_truth(h, w, day_idx=0, intervention_zones=None):
    """
    Build the true mosquito risk surface for a given DAY.
    Zone D (emerging) grows after day 28.
    intervention_zones: set of zone labels → 80% amplitude reduction.
    """
    gt = np.zeros((h, w))
    rows, cols = np.ogrid[:h, :w]
    t_mult = TEMPORAL_MULTIPLIERS[day_idx]

    for (cr, cc, amp, sig, label, kind) in HOTSPOT_DEFS:
        effective_amp = amp
        if kind == "emerging":
            if day_idx < 28:
                effective_amp = 0.0
            else:
                effective_amp = min(0.85, 0.20 * (day_idx - 27) / 4)
        if kind == "emerging_late":
            if day_idx < 45:
                effective_amp = 0.0
            else:
                effective_amp = min(0.90, 0.25 * (day_idx - 44) / 4)
        if intervention_zones and label in intervention_zones:
            effective_amp *= 0.20
        gt += effective_amp * t_mult * np.exp(
            -((rows - cr)**2 + (cols - cc)**2) / (2 * sig**2))

    gt = np.clip(gt, 0, None)
    rng = np.ptp(gt)
    gt = (gt - gt.min()) / (rng + 1e-9) if rng > 1e-9 else gt
    return gt

